# Helper function for CV + SMOTE evaluation
def evaluate_model_cv(model, x, y, model_name='Model', n_splits=5):
    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)
    accs, recalls, f1s, aucs = [], [], [], []

    for fold, (train_idx, val_idx) in enumerate(skf.split(x, y)):
        x_train, x_val = x[train_idx], x[val_idx]
        y_train, y_val = y[train_idx], y[val_idx]

        smote = SMOTE(random_state=42)
        x_res, y_res = smote.fit_resample(x_train, y_train)

        model.fit(x_res, y_res)
        y_pred = model.predict(x_val)
        y_prob = model.predict_proba(x_val)[:, 1] if hasattr(model, 'predict_proba') else y_pred

        accs.append(accuracy_score(y_val, y_pred))
        recalls.append(recall_score(y_val, y_pred))
        f1s.append(f1_score(y_val, y_pred))
        aucs.append(roc_auc_score(y_val, y_prob))

    print(f"\n{model_name} Average Results:")
    print(f"Accuracy: {np.mean(accs):.4f}, Recall: {np.mean(recalls):.4f}, F1: {np.mean(f1s):.4f}, AUC: {np.mean(aucs):.4f}\n")
    print(classification_report(y_val, y_pred))

