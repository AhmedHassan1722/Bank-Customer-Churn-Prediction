from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Dropout, BatchNormalization
from tensorflow.keras.callbacks import EarlyStopping

x_train, x_valid, y_train, y_valid = train_test_split(x, y, test_size=0.2, stratify=y, random_state=42)
smote = SMOTE(random_state=42)
x_train_res, y_train_res = smote.fit_resample(x_train, y_train)

nn_model = Sequential([
    Dense(64, activation='relu', input_shape=(x_train_res.shape[1],)),
    Dropout(0.3),
    BatchNormalization(),
    Dense(32, activation='relu'),
    Dropout(0.2),
    BatchNormalization(),
    Dense(1, activation='sigmoid')
])
nn_model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['AUC'])
early_stop = EarlyStopping(monitor='val_loss', patience=5, restore_best_weights=True)

history = nn_model.fit(x_train_res, y_train_res, epochs=30, batch_size=32,
                    validation_data=(x_valid, y_valid), callbacks=[early_stop], verbose=1)

# Evaluate NN
